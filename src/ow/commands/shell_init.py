"""`ow shell-init bash|zsh|fish` — the shell snippet: the `ow cd` wrapper and tab completion (§4).

The wrapper turns `ow cd [<ws>]` into a real `cd`: `ow cd` prints a path, the function
reads it and changes the shell's directory, while every other `ow` call reaches the
binary untouched. The completion script is generated by the vendored click's
shell-completion machinery (§14): `typer.main.get_command(app)` provides the command the
completer answers for, and the script registers the completion so `complete -p ow`
resolves once the snippet is sourced.
"""

from __future__ import annotations

import typer
from typer import _click
from typer.main import get_command

from ow import term
from ow.errors import UsageError

PROG = "ow"
COMPLETE_VAR = "_OW_COMPLETE"

# `ow cd ...` changes the shell's directory; everything else goes to the binary. The
# completion env var of the real `ow` is `_OW_COMPLETE`, which is what typer reads.
_POSIX_WRAPPER = """\
ow() {
  if [ "$1" = "cd" ]; then
    shift
    local target
    target=$(command ow cd "$@") || return
    cd "$target"
  else
    command ow "$@"
  fi
}"""

_FISH_WRAPPER = """\
function ow
    if test "$argv[1]" = cd
        set -l target (command ow cd $argv[2..-1])
        or return
        cd $target
    else
        command ow $argv
    end
end"""


def run(shell: str, *, app: typer.Typer) -> int:
    """Print the one snippet for `shell`: the `ow cd` wrapper, then the completion script."""
    if shell not in ("bash", "zsh", "fish"):
        raise UsageError(f"unsupported shell {shell!r}; expected bash, zsh or fish")
    wrapper = _FISH_WRAPPER if shell == "fish" else _POSIX_WRAPPER
    term.out(f"{wrapper}\n\n{_completion_script(app, shell)}")
    return 0


def _completion_script(app: typer.Typer, shell: str) -> str:
    """The completion script for the `ow` program, from typer's vendored click (§14)."""
    from typer.completion import completion_init

    # The app is built with add_completion=False, so nothing has registered the shell
    # classes in the vendored click yet; typer's own install path does exactly this.
    completion_init()
    completion_class = _click.shell_completion.get_completion_class(shell)
    assert completion_class is not None  # the shell name is validated above
    command = get_command(app)
    return completion_class(command, {}, PROG, COMPLETE_VAR).source().strip()
